-- Baseline schema for Code-Pal (captured from the Hibernate-managed dev database).
-- On an existing database Flyway records this as the baseline and skips it; on a fresh
-- database it is applied to create the starting schema. Later changes are additive migrations.

-- ── users ────────────────────────────────────────────────────────────────────
CREATE TABLE users (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email            varchar(255) NOT NULL,
    email_verified   boolean NOT NULL,
    enabled          boolean NOT NULL,
    provider         varchar(16) NOT NULL,
    public_id        uuid NOT NULL,
    role             varchar(16) NOT NULL,
    password_hash    varchar(60),
    name             varchar(100),
    created_at       timestamp(6) with time zone NOT NULL,
    updated_at       timestamp(6) with time zone NOT NULL,
    last_login_at    timestamp(6) with time zone,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT users_public_id_key UNIQUE (public_id),
    CONSTRAINT users_provider_check CHECK (provider IN ('LOCAL', 'GOOGLE')),
    CONSTRAINT users_role_check CHECK (role IN ('USER', 'ADMIN'))
);

-- ── workspaces ───────────────────────────────────────────────────────────────
CREATE TABLE workspaces (
    id           uuid PRIMARY KEY,
    name         varchar(120) NOT NULL,
    owner_id     bigint NOT NULL,
    personal     boolean NOT NULL,
    created_at   timestamp(6) with time zone NOT NULL,
    updated_at   timestamp(6) with time zone NOT NULL,
    deleted_at   timestamp(6) with time zone
);
CREATE INDEX ix_workspaces_owner ON workspaces (owner_id);

-- ── workspace_members ────────────────────────────────────────────────────────
CREATE TABLE workspace_members (
    id             uuid PRIMARY KEY,
    workspace_id   uuid NOT NULL,
    user_id        bigint NOT NULL,
    role           varchar(16) NOT NULL,
    created_at     timestamp(6) with time zone NOT NULL,
    CONSTRAINT uq_workspace_member UNIQUE (workspace_id, user_id),
    CONSTRAINT workspace_members_role_check CHECK (role IN ('OWNER', 'ADMIN', 'MEMBER'))
);
CREATE INDEX ix_wsmember_user ON workspace_members (user_id);

-- ── projects ─────────────────────────────────────────────────────────────────
CREATE TABLE projects (
    id                  uuid PRIMARY KEY,
    workspace_id        uuid NOT NULL,
    owner_id            bigint NOT NULL,
    name                varchar(120) NOT NULL,
    type                varchar(16) NOT NULL,
    is_public           boolean NOT NULL,
    deployment_status   varchar(16) NOT NULL,
    published_url       varchar(512),
    initial_prompt      text,
    created_at          timestamp(6) with time zone NOT NULL,
    updated_at          timestamp(6) with time zone NOT NULL,
    last_activity_at    timestamp(6) with time zone NOT NULL,
    deleted_at          timestamp(6) with time zone,
    CONSTRAINT projects_type_check CHECK (type IN ('BUILD', 'CHAT', 'PLAN')),
    CONSTRAINT projects_deployment_status_check CHECK (deployment_status IN ('NONE', 'PENDING', 'LIVE', 'FAILED'))
);
CREATE INDEX ix_projects_workspace_activity ON projects (workspace_id, last_activity_at);
CREATE INDEX ix_projects_workspace_type_activity ON projects (workspace_id, type, last_activity_at);

-- ── messages ─────────────────────────────────────────────────────────────────
CREATE TABLE messages (
    id            varchar(40) PRIMARY KEY,
    project_id    uuid NOT NULL,
    author_id     bigint,
    role          varchar(16) NOT NULL,
    status        varchar(16) NOT NULL,
    mode          varchar(16),
    reply_to_id   varchar(40),
    content       text NOT NULL,
    created_at    timestamp(6) with time zone NOT NULL,
    updated_at    timestamp(6) with time zone NOT NULL,
    CONSTRAINT messages_role_check CHECK (role IN ('USER', 'ASSISTANT', 'SYSTEM')),
    CONSTRAINT messages_status_check CHECK (status IN ('PENDING', 'STREAMING', 'COMPLETE', 'FAILED')),
    CONSTRAINT messages_mode_check CHECK (mode IN ('BUILD', 'CHAT', 'PLAN'))
);
CREATE INDEX ix_messages_project_created ON messages (project_id, created_at);

-- ── agent_runs ───────────────────────────────────────────────────────────────
CREATE TABLE agent_runs (
    id                  uuid PRIMARY KEY,
    project_id          uuid NOT NULL,
    message_id          varchar(40),
    user_id             bigint NOT NULL,
    mode                varchar(16) NOT NULL,
    status              varchar(20) NOT NULL,
    prompt_tokens       integer NOT NULL,
    completion_tokens   integer NOT NULL,
    snapshot_ref        varchar(160),
    error               text,
    created_at          timestamp(6) with time zone NOT NULL,
    updated_at          timestamp(6) with time zone NOT NULL,
    CONSTRAINT agent_runs_mode_check CHECK (mode IN ('BUILD', 'CHAT', 'PLAN')),
    CONSTRAINT agent_runs_status_check CHECK (status IN ('QUEUED', 'RUNNING', 'AWAITING_INPUT', 'DONE', 'FAILED', 'CANCELLED'))
);
CREATE INDEX ix_agent_runs_project_status ON agent_runs (project_id, status);
CREATE INDEX ix_agent_runs_status_updated ON agent_runs (status, updated_at);

-- ── agent_steps ──────────────────────────────────────────────────────────────
CREATE TABLE agent_steps (
    id           uuid PRIMARY KEY,
    run_id       uuid NOT NULL,
    seq          integer NOT NULL,
    type         varchar(16) NOT NULL,
    content      text,
    data         text,
    created_at   timestamp(6) with time zone NOT NULL,
    CONSTRAINT agent_steps_type_check CHECK (type IN ('THINKING', 'TOOL_CALL', 'TOOL_RESULT', 'ASK_USER', 'MESSAGE', 'STATUS'))
);
CREATE INDEX ix_agent_steps_run_seq ON agent_steps (run_id, seq);
